#include <stdio.h>
#include <windows.h>

int main() {
    //виставляю кодировку виводу консолі в UTF-8
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // Умова: З клавіатури вводиться послідовність чисел. 
    // Знайти суму тих із них, які кратні заданому числу (це число також вводить користувач):  

    // • Кількість чисел заздалегідь відома  

    // • Кількість чисел наперед невідома – число 0 – ознака кінця введення.  

    int divisor, count, num;
    int sum1 = 0, sum2 = 0;

    printf("Введіть число для перевірки кратності (дільник): ");
    scanf("%d", &divisor);

    if (divisor == 0) {
        printf("Помилка: ділення на нуль неможливе.\n");
        return 1;
    }

    // Варіант А: Кількість чисел заздалегідь відома
    printf("\n--- Частина 1 (відома кількість) ---\n");
    printf("Введіть кількість чисел: ");
    scanf("%d", &count);
    printf("Введіть %d чисел:\n", count);
    for (int i = 0; i < count; i++) {
        scanf("%d", &num);
        if (num % divisor == 0) {
            sum1 += num;
        }
    }
    printf("Сума кратних чисел: %d\n", sum1);

    // Варіант Б: Кількість чисел наперед невідома
    printf("\n--- Частина 2 (до введення 0) ---\n");
    printf("Вводьте числа (0 - кінець введення):\n");
    scanf("%d", &num);
    while (num != 0) {
        if (num % divisor == 0) {
            sum2 += num;
        }
        scanf("%d", &num);
    }
    printf("Сума кратних чисел: %d\n", sum2);

    return 0;
}